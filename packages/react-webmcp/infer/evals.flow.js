'use strict';

// Eval skeletons for accepted tools, in the shape Chrome's experimental
// evals-cli reads ({messages, expectedCall}). One file per tool with a direct
// query built from the tool's description and placeholder arguments; the
// developer replaces the placeholders with real values and adds the ambiguous
// phrasings that make evals worth running. Written by `infer emit --evals`.

const fs = require('fs');
const path = require('path');

import type {
  ProposalInputSchema,
  ToolProposal,
} from '../src/ReactWebMCPProposalTypes';

export type EvalFile = {
  // Relative to the evals directory.
  file: string,
  contents: string,
};

function placeholderFor(name: string, type: string): mixed {
  switch (type) {
    case 'number':
    case 'integer':
      return 1;
    case 'boolean':
      return true;
    case 'array':
      return [];
    case 'object':
      return {};
    default:
      return `<${name}>`;
  }
}

function argumentsFor(schema: ProposalInputSchema | null): {[string]: mixed} {
  const args: {[string]: mixed} = {};
  if (schema == null) {
    return args;
  }
  const names = Object.keys(schema.properties);
  for (let i = 0; i < names.length; i++) {
    const name = names[i];
    args[name] = placeholderFor(name, schema.properties[name].type);
  }
  return args;
}

function describeArguments(args: {[string]: mixed}): string {
  const names = Object.keys(args);
  if (names.length === 0) {
    return '';
  }
  const parts = names.map(name => {
    const value = args[name];
    const text = typeof value === 'string' ? value : JSON.stringify(value);
    return `${name} ${text == null ? '' : text}`;
  });
  return ` Use ${parts.join(' and ')}.`;
}

// A plain request a user might type, from the description plus the
// arguments. Trailing punctuation is normalized so the sentence reads well.
function directQueryFor(proposal: ToolProposal): string {
  const description = proposal.description.trim().replace(/\.+$/, '');
  const args = argumentsFor(proposal.inputSchema);
  return `${description}.${describeArguments(args)}`;
}

function evalFor(proposal: ToolProposal): {[string]: mixed} {
  return {
    messages: [{role: 'user', content: directQueryFor(proposal)}],
    expectedCall: [
      {
        functionName: proposal.qualifiedName,
        arguments: argumentsFor(proposal.inputSchema),
      },
    ],
  };
}

function evalFileName(proposal: ToolProposal): string {
  return proposal.qualifiedName.replace(/[^a-z0-9_]+/gi, '_') + '.eval.json';
}

const README = `# Agent tool evals

Generated by \`yarn infer-tools emit --evals\`, one file per accepted tool, in the
shape Chrome's experimental evals-cli (GoogleChromeLabs/webmcp-tools) reads:

    {"messages": [{"role": "user", "content": "..."}],
     "expectedCall": [{"functionName": "...", "arguments": {...}}]}

Each file holds a direct query with placeholder arguments such as "<sku>".
Before running them: replace the placeholders with real values, add ambiguous
phrasings ("all the meat") next to the direct ones, and give the CLI the full
tool list for the page state under test so tool selection is evaluated
realistically. Regenerating does not overwrite a file you have edited unless
you pass --force.
`;

function planEvals(accepted: Array<ToolProposal>): Array<EvalFile> {
  const files: Array<EvalFile> = [];
  const seen: Set<string> = new Set();
  const sorted = accepted
    .slice()
    .sort((a, b) =>
      a.qualifiedName < b.qualifiedName
        ? -1
        : a.qualifiedName > b.qualifiedName
          ? 1
          : 0,
    );
  for (let i = 0; i < sorted.length; i++) {
    const proposal = sorted[i];
    const file = evalFileName(proposal);
    if (seen.has(file)) {
      continue;
    }
    seen.add(file);
    files.push({
      file,
      contents: JSON.stringify(evalFor(proposal), null, 2) + '\n',
    });
  }
  if (files.length > 0) {
    files.push({file: 'README.md', contents: README});
  }
  return files;
}

// Writes the planned files under `dir`; existing files are kept unless
// `force` is set, so hand-edited evals survive a rerun. Returns what was
// written and what was left alone.
function writeEvals(
  dir: string,
  files: Array<EvalFile>,
  options?: {force?: boolean},
): {written: Array<string>, kept: Array<string>} {
  const force = options != null && options.force === true;
  const written: Array<string> = [];
  const kept: Array<string> = [];
  fs.mkdirSync(dir, {recursive: true});
  for (let i = 0; i < files.length; i++) {
    const target = path.join(dir, files[i].file);
    if (!force && fs.existsSync(target)) {
      kept.push(files[i].file);
      continue;
    }
    fs.writeFileSync(target, files[i].contents);
    written.push(files[i].file);
  }
  return {written, kept};
}

module.exports = {
  directQueryFor,
  evalFileName,
  evalFor,
  planEvals,
  writeEvals,
};
